"""Build a complete multi-page static website from a text brief.

Generates tasteful dark-styled HTML+CSS (no external dependencies, no
JavaScript frameworks — pure static files) under
C:\\Users\\sarto\\vagar\\workspace\\sites\\<name>\\ and returns the file list.
The first page is always index.html so it opens by default in a browser.

Everything stays inside the workspace jail; the site name is sanitized to
[letters, digits, dash, underscore] so no path tricks are possible.
"""
from livekit.agents.llm import function_tool

import os as _os
import re as _re

_SITES = r"C:\Users\sarto\vagar\workspace\sites"
_NAME_RE = _re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,40}$")

_CSS = """/* Generated by Vagar website builder. Dark theme, no dependencies. */
:root{--bg:#0d1117;--panel:#161b22;--text:#e6edf3;--muted:#8b949e;--accent:#58a6ff;--border:#30363d}
*{box-sizing:border-box}
body{margin:0;background:var(--bg);color:var(--text);font-family:system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;line-height:1.6}
header{background:var(--panel);border-bottom:1px solid var(--border);padding:1rem 2rem}
header h1{margin:0;font-size:1.4rem}
nav a{color:var(--accent);margin-right:1.2rem;text-decoration:none}
nav a:hover{text-decoration:underline}
main{max-width:900px;margin:0 auto;padding:2rem}
.card{background:var(--panel);border:1px solid var(--border);border-radius:8px;padding:1.5rem;margin-bottom:1.5rem}
.card h2{margin-top:0}
footer{color:var(--muted);text-align:center;padding:2rem;font-size:.85rem;border-top:1px solid var(--border)}
.btn{display:inline-block;background:var(--accent);color:#0d1117;font-weight:600;padding:.6rem 1.2rem;border-radius:6px;text-decoration:none;margin-top:1rem}
ul{padding-left:1.2rem}
"""

_PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title} — {site}</title>
<link rel="stylesheet" href="style.css">
</head>
<body>
<header>
<h1>{site}</h1>
<nav>{nav}</nav>
</header>
<main>
{body}
</main>
<footer>Built by Vagar · {site}</footer>
</body>
</html>
"""


def _page(title, pages, site, body):
    nav = "".join('<a href="%s.html">%s</a>' % (s, t) for t, s in pages)
    return _PAGE.format(title=title, site=site, nav=nav, body=body)


@function_tool(
    name="build_website",
    description="Build a complete multi-page static website from a short text brief (topic, pages, tone). Returns the created files. Use when the user asks for a website, landing page, or web page.",
)
async def build_website(name: str, brief: str) -> str:
    if not name or not _NAME_RE.match(name):
        return "Refused: site name must be 1-41 chars of letters, digits, dash, underscore."
    if not brief or not isinstance(brief, str):
        return "Need a brief describing the site."
    brief = brief.strip()[:2000]

    site_dir = _os.path.join(_SITES, name)
    _os.makedirs(site_dir, exist_ok=True)
    with open(_os.path.join(site_dir, "style.css"), "w", encoding="utf-8") as f:
        f.write(_CSS)

    # Parse the brief into pages: first line = site title; then one page per
    # "Page: <title>" line if present, else a sensible default set.
    # The first page is always index.html so it opens by default.
    titles = []
    for line in brief.splitlines():
        m = _re.match(r"\s*page\s*:\s*(.+)", line, _re.I)
        if m:
            titles.append(m.group(1).strip()[:60])
    site_title = brief.splitlines()[0].strip()[:80] if brief.splitlines() else name
    if not titles:
        titles = ["Home", "About", "Contact"]
    pages = []
    seen = set()
    for i, t in enumerate(titles):
        slug = "index" if i == 0 else _re.sub(r"[^a-z0-9]+", "-", t.lower()).strip("-")
        if not slug or slug in seen:
            slug = "page%d" % (i + 1) if i else "index"
        seen.add(slug)
        pages.append((t, slug))

    made = ["style.css"]
    for i, (ptitle, slug) in enumerate(pages):
        body = (
            '<div class="card"><h2>%s</h2>\n'
            "<p>%s</p>\n"
            '<a class="btn" href="%s.html">Read more</a></div>\n'
            % (ptitle, brief[:400].replace("\n", " "),
               pages[(i + 1) % len(pages)][1])
        )
        html = _page(ptitle, pages, site_title, body)
        fname = slug + ".html"
        with open(_os.path.join(site_dir, fname), "w", encoding="utf-8") as f:
            f.write(html)
        made.append(fname)

    return (
        "Built site '%s' (%d pages) under workspace\\sites\\%s\\:\n%s\n"
        "Open %s\\index.html in a browser to view it."
        % (site_title, len(pages), name, "\n".join("- " + m for m in made), site_dir)
    )
